CREATE TABLE import_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source VARCHAR(32) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_hash CHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    total_count INT NOT NULL DEFAULT 0,
    duplicate_count INT NOT NULL DEFAULT 0,
    error_message VARCHAR(1000),
    created_at TIMESTAMP NOT NULL,
    confirmed_at TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_import_batch_file_hash UNIQUE (file_hash)
);

CREATE TABLE category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_category_name UNIQUE (name)
);

CREATE TABLE category_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    category_id BIGINT NOT NULL,
    source VARCHAR(32),
    keyword VARCHAR(255),
    priority INT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT fk_category_rule_category FOREIGN KEY (category_id) REFERENCES category (id)
);

CREATE TABLE finance_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    import_batch_id BIGINT NOT NULL,
    source VARCHAR(32) NOT NULL,
    external_id VARCHAR(128),
    business_fingerprint CHAR(64) NOT NULL,
    occurred_at TIMESTAMP NOT NULL,
    direction VARCHAR(16) NOT NULL,
    amount DECIMAL(19,4) NOT NULL,
    account_name VARCHAR(255),
    counterparty VARCHAR(255),
    summary VARCHAR(1000),
    category VARCHAR(100),
    category_id BIGINT,
    category_origin VARCHAR(16) NOT NULL DEFAULT 'UNCLASSIFIED',
    raw_data JSON,
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_transaction_source_external UNIQUE (source, external_id),
    CONSTRAINT uk_transaction_fingerprint UNIQUE (business_fingerprint),
    CONSTRAINT fk_transaction_import_batch FOREIGN KEY (import_batch_id) REFERENCES import_batch (id),
    CONSTRAINT fk_transaction_category FOREIGN KEY (category_id) REFERENCES category (id)
);

CREATE INDEX idx_transaction_occurred_at ON finance_transaction (occurred_at);
CREATE INDEX idx_transaction_direction_occurred_at ON finance_transaction (direction, occurred_at);
CREATE INDEX idx_category_rule_active_priority ON category_rule (active, priority);
